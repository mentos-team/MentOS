/// One translation unit holds the glyph data so that a build with more than one
/// graphical backend links one copy of it. The arrays are private: a backend
/// reaches a glyph through the descriptor, which is what keeps the two
/// dimensions and the bitmap that belongs to them from ever disagreeing.
///
/// This file lives beside video.c rather than in src/io/video/ because the build
/// filters that whole directory down to the single selected backend. A shared
/// asset is not a backend, and keeping it out of there is what lets that filter
/// stay a rule about a directory instead of a list of exceptions.

#include "io/video/video_font.h"

